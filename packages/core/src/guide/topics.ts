/** The topic whose id or title matches the query, ignoring case and surrounding spaces. */
export const findGuideTopic = (query: string): GuideTopic | undefined => {
  const wanted = query.trim().toLowerCase();
  if (wanted.length === 0) return undefined;
  return GUIDE_TOPICS.find(
    (topic) => topic.id.toLowerCase() === wanted || topic.title.toLowerCase() === wanted,
  );
};
